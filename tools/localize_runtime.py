def translate(data, catalog):
    data = bytearray(data)
    for es, en in sorted(catalog.items(), key=lambda item: -len(item[0])):
        old, new = glyphs(es), glyphs(en)
        assert len(new) <= len(old), (es, en)
        offsets = [i for i in range(len(data)) if data[i:i + len(old)] == old]
        assert len(offsets) == (4 if es == 'VOLVER' and catalog is RUNTIME2 else 1), (es, offsets)
        for i in offsets:
            data[i:i + len(old)] = new.ljust(len(old), b'\x5f')
    return bytes(data)


def write_boot_include(path, segment):
    """English game 3rd segment also holds runtime2 and the code messages."""
    path.write_text(f'''; Generated by tools/localize_runtime.py.
; Called after selection, before music. Runs from the intro in page 2.
in_apply_language:
        ld a,(rt_language)
        or a
        ret z
        di
        ld hl,in_english_banks
        ld de,rt_bank_segs
        ld bc,8
        ldir
        ld a,{segment}
        ld (rt_game_segment0+1),a
        inc a
        ld (rt_game_segment1+1),a
        inc a
        ld (rt_game_segment2+1),a
        ld (rt_seg),a
        ld hl,0x6000
        ld de,RT2_BASE
        ld bc,RT2_SIZE
        call rt_copy
        ld hl,0x6C00
        ld de,rt_spell_prompt_wizard
        ld bc,sc_txt_end-rt_spell_prompt_wizard
        call rt_copy
        ei
        ret
in_english_banks:
        db 0,{segment+3},{segment+6},{segment+4},SEG_BANK4,{segment+7},{segment+5},SEG_BANK7
''')
