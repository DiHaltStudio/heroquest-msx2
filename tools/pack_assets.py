#!/usr/bin/env python3
"""Packs the PNG sheets of assets/ into the VRAM images that the ROM carries.

Called by build_rom.py. Returns the blobs (name, VRAM address, bytes) and
writes build/gfx.inc with the positions of every graphic inside the sheets.

VRAM layout (SCREEN 5, four pages of 256 x 256):
  page 0   the screen (and the sprite tables in its hidden lines)
  page 1   the scene, and a scratch area in its hidden lines
  page 2   sheet: hero frames (10 per row, 24 x 40 cells), furniture slot
  page 3   sheet: floor tiles, wall strips and doors, monsters, frame edge
           strips, font, overview-map glyphs, marks and room floors
"""
import json
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, 'assets')
from original_paths import ZX_ORIG


class Page:
    def __init__(self):
        self.px = [[0] * 256 for _ in range(256)]
        self.used = 0

    def paste(self, im, x0, y0, box=None):
        if box:
            im = im.crop(box)
        w, h = im.size
        src = im.load()
        for y in range(h):
            for x in range(w):
                self.px[y0 + y][x0 + x] = src[x, y] & 15
        self.used = max(self.used, y0 + h)

    def data(self):
        out = bytearray()
        for y in range(self.used):
            row = self.px[y]
            for x in range(0, 256, 2):
                out.append(row[x] << 4 | row[x + 1])
        return bytes(out)


def view_runs():
    """Cells of the room window: the 17 runs of the game's ViewAttrRuns
    table (C528h) as (row, column, cells)."""
    game = open(str(ZX_ORIG / 'block05_flagFF.bin'), 'rb').read()
    out = []
    for i in range(17):
        o = 0xC528 - 0x6400 + 3 * i
        a = (game[o] | game[o + 1] << 8) - 0x5800
        out.append((a // 32, a % 32, game[o + 2] + 1))
    return out


def load(name):
    im = Image.open(os.path.join(ASSETS, name))
    assert im.mode == 'P', '%s must stay an indexed PNG' % name
    return im


def pack():
    inc = ['; Generated by tools/pack_assets.py: positions inside the VRAM sheets', '']
    game = open(str(ZX_ORIG / 'block05_flagFF.bin'), 'rb').read()
    p3 = Page()
    floor = load('floor.png')
    inc.append('rt_floor_pos:               ; x, y in page 3 of the 7 floor tiles')
    for n in range(7):
        x, y = 48 * (n % 5), 24 * (n // 5)
        p3.paste(floor, x, y, (48 * n, 0, 48 * n + 48, 24))
        inc.append('        db %d,%d' % (x, y))
    p3.paste(load('walls_doors.png'), 0, 48)
    inc.append('WALL_SY         equ 48      ; wall strips and doors: x = 24 * number')
    p3.paste(load('monsters.png'), 0, 98)
    inc.append('MONSTER_SY      equ 98      ; monsters, chest, throne: x = 24 * number')
    # font: 69 glyphs, 32 per row, white (15) on 0
    font = load('font.png')
    for n in range(69):
        p3.paste(font, 8 * (n % 32), 168 + 8 * (n // 32),
                 (8 * (n % 16), 8 * (n // 16), 8 * (n % 16) + 8, 8 * (n // 16) + 8))
    inc.append('FONT_SY         equ 168     ; font in page 3: 32 glyphs per row')
    # overview-map glyphs (coloured) after the font, 32 per row: glyph n is
    # at cell 69 + n
    mg = load('map_glyphs.png')
    assert mg.width == 8 * 34, 'map_glyphs.png: 34 glyphs of 8 x 8 (the last one is the Death Mist of the expansion)'
    for n in range(34):
        k = 69 + n
        p3.paste(mg, 8 * (k % 32), 168 + 8 * (k // 32), (8 * n, 0, 8 * n + 8, 8))
    inc.append('MAPGLYPH_SY     equ 184     ; overview-map glyph n: cell n + 5 of this row, the next row from cell 32 on')
    # map floor of the rooms: rooms 0-31 in one row, rooms 32-39 after the
    # last map glyphs
    mf = load('map_floor.png')
    p3.paste(mf, 0, 248, (0, 0, 256, 8))
    p3.paste(mf, 56, 192, (256, 0, 320, 8))
    inc.append('MAPFLOOR_SY     equ 248     ; map floor of room r < 32 at x = 8r; rooms 32-39 at x = 8(r - 25), y = 192')
    # the 17 large furniture marks, 10 per row
    mo = load('map_objects.png')
    inc.append('rt_mapobj_tab:              ; per large mark: sheet x, y, width, height in pixels')
    for n in range(17):
        o = 0x9470 - 0x6400 + 8 * n
        w, h = game[o + 6] * 8, game[o + 7]
        x, y = 24 * (n % 10), 200 + 24 * (n // 10)
        p3.paste(mo, x, y, (24 * n, 0, 24 * n + 24, 24))
        inc.append('        db %d,%d,%d,%d' % (x, y, w, h))
    inc.append('ZX_MAPGLYPHS    equ 0xB1C0')
    inc.append('ZX_MAPOBJTAB    equ 0x9470')
    # table from the Spectrum graphic address of a sprite to its place in
    # the sheets: address, page, x, y. The y is that of the first line of the
    # graphic (the cells are bottom aligned).
    def frame(n):
        o = 0xC23A - 0x6400 + 4 * n
        return game[o], game[o + 1], game[o + 2] | game[o + 3] << 8
    gfx = {}
    for n in range(0x10, 0x40):             # heroes: page 2
        w, h, addr = frame(n)
        k = n - 0x10
        gfx[addr] = (2, 24 * (k % 10), 40 * (k // 10) + 40 - h)
    for k, n in enumerate(list(range(8)) + [0x40, 0x41]):   # monsters, chest, throne
        w, h, addr = frame(n)
        gfx[addr] = (3, 24 * k, 98 + 40 - h)
    for i in range(8):                      # doors (24 x 50)
        gfx[0xC6EB + 150 * i] = (3, 24 * (2 + i), 48)
    inc.append('rt_gfx_tab:                 ; Spectrum graphic address, sheet page, x, y; 0 ends')
    for addr in sorted(gfx):
        inc.append('        dw 0x%04X' % addr)
        inc.append('        db %d,%d,%d' % gfx[addr])
    inc.append('        dw 0')
    p2 = Page()
    heroes = load('heroes.png')
    for n in range(48):
        p2.paste(heroes, 24 * (n % 10), 40 * (n // 10),
                 (24 * (n % 12), 40 * (n // 12), 24 * (n % 12) + 24, 40 * (n // 12) + 40))
    # Last hero row has two unused cells: 48 x 40 pixels, above the
    # furniture cache (y=200). 20 paper tiles, eight border pieces and an
    # 8x8 scratch cell for transparent, recoloured font glyphs fit here.
    scrolls = load('scrolls.png')
    assert scrolls.size == (48, 40), 'scrolls.png: 6 x 5 tiles of 8x8'
    p2.paste(scrolls, 192, 160)
    styles = json.load(open(os.path.join(ASSETS, 'scrolls.json')))
    assert len(styles['styles']) == 10 and len(styles['paper_to_style']) == 16
    assert all(0 <= n < 10 for n in styles['paper_to_style'])
    assert all(1 <= s['ink'] <= 15 for s in styles['styles']), 'scroll ink 0 is transparent'
    with open(os.path.join(ROOT, 'build', 'scroll_styles.inc'), 'w') as f:
        f.write('; Generated from assets/scrolls.json\nsc_families:\n        db ')
        f.write(','.join(str(n) for n in styles['paper_to_style']))
        f.write('\nsc_inks:\n        db ')
        f.write(','.join(str(s['ink']) for s in styles['styles']))
        f.write('\n')
    inc += ['SCROLL_SX       equ 192', 'SCROLL_SY       equ 160',
            'SCROLL_SCRATCH_X equ 224', 'SCROLL_SCRATCH_Y equ 192']
    # The three left-hand HUD symbols keep their original 8x8 outlines,
    # with native colour shading. The remaining unused strip is beside
    # the scroll atlas, above the furniture cache.
    hud = load('hud_icons.png')
    assert hud.size == (8, 24), 'hud_icons.png: gold, movement, body; 8x8 each'
    p2.paste(hud, 240, 160)
    inc += ['HUD_ICON_X      equ 240', 'HUD_ICON_Y      equ 160']
    inc.append('HERO_PER_ROW    equ 10      ; hero frames in page 2: 24 x 40 cells')
    # Art of the frame inside the cells of the room window. The game fills
    # those cells (black) every time it draws a room, so whatever the frame
    # has there is kept as small strips that are drawn over the window after
    # it is filled. The window itself is the white area of frame.png around
    # its centre; everything else in those cells is art.
    fr = load('frame.png')
    fpx = fr.load()
    window = set()
    stack = [(128, 96)]
    assert fpx[128, 96] == 15, 'frame.png: the room window must be white (15)'
    while stack:
        x, y = stack.pop()
        if (x, y) in window or not (0 <= x < 256 and 0 <= y < 192) or fpx[x, y] != 15:
            continue
        window.add((x, y))
        stack += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    runs = view_runs()
    segs = []
    for row, col, n in runs:
        for k in range(n):
            r, c = row + (col + k) // 32, (col + k) % 32
            ink = any((c * 8 + x, r * 8 + y) not in window for y in range(8) for x in range(8))
            if ink and segs and segs[-1][0] == r and segs[-1][1] + segs[-1][2] == c:
                segs[-1][2] += 1
            elif ink:
                segs.append([r, c, 1])
    inc.append('EDGE_COUNT      equ %d' % len(segs))
    inc.append('rt_edge_tab:                ; column, row, sheet x, sheet y (page 3), cells')
    ex, ey = 0, 138
    for r, c, n in segs:
        if ex + n * 8 > 256:
            ex, ey = 0, ey + 8
        assert ey + 8 <= 168, 'frame.png: too much art inside the room window cells'
        strip = fr.crop((c * 8, r * 8, (c + n) * 8, r * 8 + 8))
        spx = strip.load()
        for y in range(8):
            for x in range(n * 8):
                if (c * 8 + x, r * 8 + y) in window:
                    spx[x, y] = 0           # transparent: the window shows through
        p3.paste(strip, ex, ey)
        inc.append('        db %d,%d,%d,%d,%d' % (c, r, ex, ey, n))
        ex += n * 8
    # hardware sprite pointer: one sprite plane per colour (at most two)
    cur = load('cursor.png')
    cpx = cur.load()
    cols = sorted(set(cpx[x, y] for y in range(16) for x in range(16)) - {0})
    assert len(cols) <= 2, 'cursor.png: at most two colours besides colour 0'
    cols += [cols[-1]] * (2 - len(cols))
    planes, colours = [], []
    for c in cols:
        left = [sum((0x80 >> x) for x in range(8) if cpx[x, y] == c) for y in range(16)]
        right = [sum((0x80 >> x) for x in range(8) if cpx[8 + x, y] == c) for y in range(16)]
        planes += left + right
        colours += [c] * 16
    inc.append('rt_cursor_patterns:         ; 2 sprites of 16 x 16')
    for i in range(0, 64, 16):
        inc.append('        db ' + ','.join('0x%02X' % b for b in planes[i:i + 16]))
    inc.append('rt_cursor_colours:          ; one colour per line and sprite')
    for i in range(0, 32, 16):
        inc.append('        db ' + ','.join('%d' % b for b in colours[i:i + 16]))
    frame = Page()
    frame.paste(fr, 0, 0)
    parch = Page()
    parch.paste(load('parchment.png'), 0, 0)
    # Graphics loaded on demand into a rectangle of VRAM: the furniture piece
    # of the room (one at a time, like the original's single buffer) and the
    # combat pictures. Each is stored as its rows, 2 pixels per byte.
    def rect(im, box):
        c = im.crop(box)
        px = c.load()
        out = bytearray()
        for y in range(c.height):
            for x in range(0, c.width, 2):
                out.append((px[x, y] & 15) << 4 | (px[x + 1, y] & 15))
        return bytes(out)
    furn = load('furniture.png')
    pics = load('pictures.png')
    rects = [('furn%02d' % n, rect(furn, (48 * n, 0, 48 * n + 48, 48))) for n in range(17)]
    # The game asks for its ten pictures by number (rt_pic_ids): 0 skeleton,
    # 1 fimir, 2 wizard wounded, 3 chaos warrior, 4 zombie and mummy, 5
    # goblin and orc, 6 attack blocked, 7 elf wounded, 8 dwarf wounded, 9
    # barbarian wounded. PIC_CELL says which cell of pictures.png (five per
    # row) each one shows: the four hero drawings of the sheet are the
    # armoured warrior (cell 2), the cloaked figure (7), the bearded wizard
    # (8) and the pale face (9).
    PIC_CELL = [0, 1, 8, 3, 4, 5, 6, 9, 7, 2]
    rects += [('pic%d' % n, rect(pics, (128 * (c % 5), 64 * (c // 5), 128 * (c % 5) + 128, 64 * (c // 5) + 64)))
              for n, c in enumerate(PIC_CELL)]
    # the two fonts as rectangles for the options menu: the 64 glyphs of
    # the first two sheet rows (256 x 16) and the last five (40 x 8)
    for k, name in enumerate(('font.png', 'font_alt.png')):
        f = load(name)
        fp = Page()
        for n in range(69):
            fp.paste(f, 8 * (n % 32), 8 * (n // 32),
                     (8 * (n % 16), 8 * (n // 16), 8 * (n % 16) + 8, 8 * (n // 16) + 8))
        sheet = Image.new('P', (256, 24))
        spx = sheet.load()
        for y in range(24):
            for x in range(256):
                spx[x, y] = fp.px[y][x]
        rects.append(('font%da' % k, rect(sheet, (0, 0, 256, 16))))
        rects.append(('font%db' % k, rect(sheet, (0, 16, 40, 24))))
    inc.append('rt_furn_addrs:              ; bank 6 address of the 17 furniture graphics (objects 4Bh-5Bh)')
    for n in range(17):
        o = 0x886F                          # placeholder, replaced below
    furn_tab = 0
    for n in range(17):
        o = 0x88A0 - 0x6400 + 6 * n + 4
        inc.append('        dw 0x%04X' % (game[o] | game[o + 1] << 8))
    inc.append('rt_pic_ids:                 ; RAM bank and address of the 10 combat pictures')
    pictures = [(3, 0xF382), (3, 0xF802), (7, 0xC440), (7, 0xC8C0),
                (4, 0xE400), (4, 0xE880), (4, 0xED00), (4, 0xF180),
                (4, 0xF600), (4, 0xFA80)]
    for bank, addr in pictures:
        inc.append('        db %d' % bank)
        inc.append('        dw 0x%04X' % addr)
    # Studio logo shown at boot: assets/dihalt_logo.png (any size, RGB) is
    # scaled to the whole 256 x 212 screen and reduced to its own 16 colours
    # of the V9938 palette (3 bits per channel).
    logo = Image.open(os.path.join(ASSETS, 'dihalt_logo.png')).convert('RGB')
    logo = logo.resize((256, 212), Image.LANCZOS)
    # every pixel snapped to the 512 colours of the VDP; the palette takes
    # the most used colours that are clearly different from each other (so a
    # thin stripe of its own colour is not lost to shades of the big areas)
    # and every pixel goes to the nearest of them
    lsrc = logo.load()
    snap = [[tuple((v * 7 + 127) // 255 for v in lsrc[x, y]) for x in range(256)] for y in range(212)]
    count = {}
    for row in snap:
        for c in row:
            count[c] = count.get(c, 0) + 1
    ranked = [c for c, _ in sorted(count.items(), key=lambda kv: -kv[1])]
    lpal = []
    for far in (12, 6, 3, 1):               # distinct colours first, then closer ones
        for c in ranked:
            if len(lpal) < 16 and all(sum((a - b) ** 2 for a, b in zip(c, p)) >= far for p in lpal):
                lpal.append(c)
    lpal += [(0, 0, 0)] * (16 - len(lpal))
    near = {}
    def nearest(c):
        if c not in near:
            near[c] = min(range(16), key=lambda i: sum((a - b) ** 2 for a, b in zip(c, lpal[i])))
        return near[c]
    lidx = [[nearest(c) for c in row] for row in snap]
    ldata = bytearray()
    for y in range(212):
        for x in range(0, 256, 2):
            ldata.append(lidx[y][x] << 4 | lidx[y][x + 1])
    lp3 = [v for c in lpal for v in c]
    inc.append('rt_logo_palette:            ; 16 entries: R << 4 | B, G')
    inc.append('        db ' + ','.join('0x%02X,0x%02X' % (lp3[3 * i] << 4 | lp3[3 * i + 2], lp3[3 * i + 1])
                                        for i in range(16)))
    inc.append('LOGO_BORDER     equ %d      ; colour of the top-left pixel' % lidx[0][0])
    blobs = [('logo', 0x00000, bytes(ldata)),
             ('sheet3', 0x18000, p3.data()),
             ('sheet2', 0x10000, p2.data()),
             ('frame', 0x08000 + 10 * 128, frame.data()),     # page 1, 10 lines down
             ('parch', 0x08000 + 10 * 128, parch.data())]
    return blobs, inc, rects


def palette_bytes():
    """V9938 palette entries (R << 4 | B, G) of assets/palette.json."""
    import json
    cols = json.load(open(os.path.join(ASSETS, 'palette.json')))['colours']
    out = bytearray()
    for r, g, b in cols:
        r, g, b = [(v * 7 + 127) // 255 for v in (r, g, b)]
        out += bytes([r << 4 | b, g])
    return bytes(out)
