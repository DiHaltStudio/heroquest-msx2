def build(base):
    source = (ZX_ORIG / 'block08_flag0D.bin').read_bytes()
    if sha256(source).hexdigest() != SOURCE_SHA256:
        raise SystemExit('Unsupported sound bank. Run tools/check_originals.py.')
    image = bytearray()
    cursor = 0
    for start, end, replacement in PATCHES:
        image.extend(source[cursor:start])
        image.extend(bytes.fromhex(replacement))
        cursor = end
    image.extend(source[cursor:0x2304])
    assert len(image) == 8975
    delta = base - 0xC000
    for offset in RELOCATIONS:
        value = (int.from_bytes(image[offset:offset + 2], 'little') + delta) & 0xFFFF
        image[offset:offset + 2] = value.to_bytes(2, 'little')
    build_dir = Path(__file__).resolve().parents[1] / 'build'
    build_dir.mkdir(exist_ok=True)
    (build_dir / 'sound.bin').write_bytes(image)
    labels = {'Tune2OrderA': 0x0959, 'Tune2OrderB': 0x0993,
              'Tune2OrderC': 0x09CD, 'SoundDriverEntry': 0x1388}
    (build_dir / 'sound.sym').write_text(''.join(
        f'{name}: equ {base + offset:08X}h\n' for name, offset in labels.items()))
    return bytes(image), base + 0x1388
